export class FabricCatalogService {
  getAllFabrics(): LuxuryFabricSwatch[] {
    return LUXURY_FABRIC_CATALOG;
  }

  getFabricById(id: string): LuxuryFabricSwatch | undefined {
    return LUXURY_FABRIC_CATALOG.find((f) => f.id === id || f.code === id);
  }

  filterFabrics(filters: {
    mill?: string;
    season?: string;
    weavePattern?: string;
    color?: string;
    maxPrice?: number;
  }): LuxuryFabricSwatch[] {
    return LUXURY_FABRIC_CATALOG.filter((f) => {
      if (filters.mill && f.mill !== filters.mill) return false;
      if (filters.season && f.season !== filters.season && f.season !== 'ALL_SEASON') return false;
      if (filters.weavePattern && f.weavePattern !== filters.weavePattern) return false;
      if (filters.maxPrice && f.pricePerMeter > filters.maxPrice) return false;
      return true;
    });
  }
}

export const fabricCatalogService = new FabricCatalogService();
